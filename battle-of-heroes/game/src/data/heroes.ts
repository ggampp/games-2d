export function getHero(id: number): HeroDef {
  const hero = HEROES.find((h) => h.id === id);
  if (!hero) throw new Error(`Hero ${id} not found`);
  return hero;
}

export function scaledHero(hero: HeroDef, level: number): HeroDef {
  const m = 1 + (level - 1) * 0.12;
  return {
    ...hero,
    hp: Math.round(hero.hp * m),
    atk: Math.round(hero.atk * m),
    def: Math.round(hero.def * m),
  };
}
